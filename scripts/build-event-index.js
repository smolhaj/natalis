#!/usr/bin/env node
/**
 * build-event-index.js — classify every event from its unminified source and
 * write the result to src/data/eventIndex.generated.js.
 *
 * `classifyEvent` reads guard source text (`G.mem`, `G.flags`, `G.place` …),
 * and the production build renames the parameter and lowers optional chaining,
 * so in the shipped bundle that reading found nothing. This runs on the source,
 * before `vite build`, and the game ships the answer as data. See the comment
 * above `classifyEvent` in src/data/events.js.
 *
 *   node scripts/build-event-index.js          write the index
 *   node scripts/build-event-index.js --check  exit 1 if the index is stale
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { registerResolveHooks } from './lib/register.js'

registerResolveHooks()
globalThis.__NATALIS_RAW_CLASSIFY = true

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'src/data/eventIndex.generated.js')
const FIELDS = ['departs', 'writtenForAbroad', 'assumesSchool', 'assumesInstitutions',
  'anchored', 'continuesMem', 'continuesFlag', 'specificity', 'dated', 'register']

const { EVENTS, classifyEventRaw } = await import('../src/data/events.js')
const { CAREERS } = await import('../src/data/careers.js')
const { LIFE_SKELETON_EVENTS } = await import('../src/data/events/lifecycle/events_life_skeleton.js')
const { PHASE_ENTRY_EVENTS } = await import('../src/data/events/lifecycle/events_phase_entries.js')

// Everything that can reach classifyEvent: the corpus, career events, and the
// scheduled beats the engine queues directly.
const all = [...EVENTS, ...LIFE_SKELETON_EVENTS, ...PHASE_ENTRY_EVENTS]
for (const c of CAREERS) for (const e of c.events ?? []) all.push(e)

const rows = {}
const dupes = []
for (const e of all) {
  if (!e || !e.id) continue
  // Fields some modules declare by hand are kept, since raw classification
  // respects them too; computed ones are cleared so this is a fresh read.
  classifyEventRaw(e)
  const row = FIELDS.map(f => (e[f] === undefined ? null : e[f]))
  while (row.length && (row[row.length - 1] === null || row[row.length - 1] === false)) row.pop()
  if (rows[e.id] && JSON.stringify(rows[e.id]) !== JSON.stringify(row)) dupes.push(e.id)
  rows[e.id] = row
}

const ids = Object.keys(rows).sort()
const body = ids.map(id => `${JSON.stringify(id)}:${JSON.stringify(rows[id])}`).join(',\n')
const text = `// GENERATED by scripts/build-event-index.js from unminified source. Do not edit.\n` +
  `// Field order: ${FIELDS.join(', ')}\n` +
  `export default {\n${body}\n}\n`

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (cur !== text) {
    console.error('eventIndex.generated.js is stale — run `node scripts/build-event-index.js`')
    process.exit(1)
  }
  console.log(`event index up to date (${ids.length} events)`)
} else {
  fs.writeFileSync(OUT, text)
  console.log(`wrote ${ids.length} events to ${path.relative(ROOT, OUT)}${dupes.length ? ` — ${dupes.length} ids classified differently in two places: ${dupes.slice(0, 5).join(', ')}` : ''}`)
}
