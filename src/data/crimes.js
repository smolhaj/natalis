// ─────────────────────────────────────────────────────────────────────────────
// Crime in natalis is a thing people do when the other doors are shut. It is not
// a career path and it is not a joke.
//
// Two things were wrong here and both are fixed below.
//
// 1. The money. Payouts were flat dollars everywhere — a lifted wallet paid the
//    same $2,000 in Chad as in Chicago, which is several years of a Chadian
//    doctor's salary. Salaries already scale by GDP tier where they are paid, so
//    every payout now scales with them through `crimePayout()`. A wallet holds
//    what a wallet in that street holds.
//
// 2. The odds. Arrest risk was low enough that repeat crime was the best income
//    in the game. Every risk below has been raised. Getting away with it is now
//    the exception, and the run of good years before the arrest is the shape of
//    the thing — which is also how it goes.
//
// The register is the house register: name the act, name what it costs, and stop.
// No emoji, no scare quotes, no winking at the player.
// ─────────────────────────────────────────────────────────────────────────────

// Payouts are written in wealthy-tier dollars. Charge them through crimePayout().
export const CRIME_GDP_MULT = {
  very_high: 1.0,
  high: 0.7,
  medium_high: 0.45,
  medium: 0.28,
  low_medium: 0.14,
  low: 0.08,
  very_low: 0.05,
}

export function crimePayout(base, gdpTier) {
  return Math.round((base * (CRIME_GDP_MULT[gdpTier] ?? 1)) / 10) * 10
}

// The country the character is living in now, not the one they were born in.
function liveGdp(p) {
  return p?._state?.currentCountry?.gdp ?? p?._state?.character?.country?.gdp ?? 'very_high'
}

